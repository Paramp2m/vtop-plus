#!/usr/bin/env node
// One-off (PLAN.md M2): reads ViBoot's ref/Viboot/js/captcha/bitmaps.js and
// writes only the neural solver's `weights` (528×32) and `biases` (32) to
// src/content/captcha/model.js. The 34 bitmap masks (the vtopcc matcher,
// dropped with vtopcc, D7) are left out. ref/ is only read, never written.

import { readFile, mkdir, writeFile } from "node:fs/promises";
import { runInNewContext } from "node:vm";
import { fileURLToPath } from "node:url";

const REF = fileURLToPath(new URL("../ref/Viboot/js/captcha/bitmaps.js", import.meta.url));
const OUT_DIR = fileURLToPath(new URL("../src/content/captcha/", import.meta.url));

// bitmaps.js is a plain `const bitmaps = {…}` data file; evaluate it in an
// empty context and hand the object back.
const code = (await readFile(REF, "utf8")).replace(/^﻿/, "");
const { weights, biases } = runInNewContext(`${code}\n;bitmaps`, Object.create(null));

const shape = (m) => `${m.length}×${m[0].length}`;
if (weights.length !== 528 || weights.some((row) => row.length !== 32)) throw new Error(`weights ${shape(weights)}`);
if (biases.length !== 32) throw new Error(`biases ${biases.length}`);
if (![...weights.flat(), ...biases].every(Number.isFinite)) throw new Error("non-finite value");

const header = `// Generated by tools/extract-captcha-model.mjs from ViBoot 2.1.15
// js/captcha/bitmaps.js (\`weights\` and \`biases\` only). Do not edit.
"use strict";

`;
const body = `globalThis.ViBoot.captchaModel = {\n  weights: [\n${weights
  .map((row) => `    ${JSON.stringify(row)},`)
  .join("\n")}\n  ],\n  biases: ${JSON.stringify(biases)},\n};\n`;

await mkdir(OUT_DIR, { recursive: true });
await writeFile(`${OUT_DIR}model.js`, header + body);
console.log(`model.js: weights ${shape(weights)}, biases ${biases.length}`);
